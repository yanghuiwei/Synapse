-- ============================================================
-- Reqly 002_folder_auth.sql —— 文件夹级授权配置
-- ------------------------------------------------------------
-- design.md §4.4 的「继承父级」要求「沿文件夹树向上找最近的 auth 配置」，
-- 而 001 的 folder 表只有 `is_token_source` —— 那是「Token 源分组」标记，
-- 与「授权配置」是两件事（一个分组可以有 Token 源，授权却未必用 Bearer）。
--
-- 不加这一列，「继承父级」在界面上就是个**死选项**：
-- 一个画出来但不生效的选项比没有还糟（P3 搜索框那条教训）。
--
-- 形状与 `request.auth` 完全一致（JSON、camelCase、`{"type": ...}` 内部标签）。
-- 默认 `{}` 表示「未配置」—— 与老库里 request.auth 的存量值语义一致，
-- 读出来都会退化成「不注入任何授权」。
-- ============================================================

ALTER TABLE folder ADD COLUMN auth TEXT NOT NULL DEFAULT '{}';
