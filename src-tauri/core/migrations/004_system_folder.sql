-- ============================================================
-- Reqly 004_system_folder.sql —— 系统分类（不可删除的特殊分类）
-- ------------------------------------------------------------
-- 背景：Token 来源原先要求「先建一个分类，把登录接口放进去，再配 Token」，
-- 三跳才走得到。现在改成**每个工作区固定有一个「token刷新」分类**：
-- Token 来源永远配在它下面，不管请求挂在哪个分类（甚至没挂分类）都用得上。
--
-- 于是需要一个「这个分类是系统建的、用户不能删/改名/移动」的标记。
-- 为什么不复用 `is_token_source`：那个是**引导标记**，改造前在集合树右键菜单里
-- 能随手打上/取消（菜单项已删，但这一位的语义仍是「引导」而非「保护」），
-- 拿它当保护条件就是两件事共用一位，用户随手一取消保护就没了。
-- 两个标记的含义也真的不同 ——
-- 系统分类**是** Token 分组（建的时候顺手把 is_token_source 也置 1），
-- 但并非每个 Token 分组都不可删。
--
-- 索引为什么是**部分索引**（`WHERE is_system = 1`）而不是普通的
-- `(workspace_id, is_system)`：后者对 `is_system = 0` 的那一大片行
-- 也会要求唯一 —— 第二个普通分类就插不进去了。
-- 加上这个谓词之后它的语义才准确：**每个工作区最多一个系统分类**。
-- 「只有一个」是硬约束，交给数据库兜底比靠调用方自觉可靠。
--
-- 存量库跑到这里时 `is_system` 取默认值 0（全是普通分类），
-- 系统分类由启动路径 `folder::ensure_system_folder` 补建。
-- ============================================================

ALTER TABLE folder ADD COLUMN is_system INTEGER NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX idx_folder_system ON folder(workspace_id) WHERE is_system = 1;
