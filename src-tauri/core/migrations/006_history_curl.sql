-- ============================================================
-- Reqly 006_history_curl.sql —— 历史里留一份「当时真实发出的是什么」
-- ------------------------------------------------------------
-- 排查 401 / 400 的时候，要看的**不是**编辑框里的 `{{token.access}}`，
-- 而是那一刻被解析之后的真值：URL 展开成了什么、Authorization 到底在不在、
-- 发出去的 body 是哪一版。这些信息只在发送的那一瞬间存在
-- （`Pipeline::prepare` 之后、`execute` 之前），发送完就没了。
--
-- 为什么必须落库、而不是每次回看时现算：token 会过期、环境变量会被改。
-- 拿今天的变量去重算昨天那次请求，得到的 curl 与当时发出去的**不是一回事**——
-- 而要解释的恰恰是「当时」那个 401。
--
-- 两列：明文那列是给用户看自己的请求（本机 SQLite，与 `token_cache.access_token`
-- 一直明文存着是同一个口径），打码那列给「要截图 / 要贴给别人」的场合。
-- 判定名单在 `redact.rs`，只有那一份。
--
-- 存量为 NULL = 那条历史发生在本版之前。前端会退化成「按当前内容重新生成」
-- 并明确标出来源，而不是拿一个空值假装那就是当时发出去的东西。
-- ============================================================

ALTER TABLE history ADD COLUMN curl        TEXT;
ALTER TABLE history ADD COLUMN curl_masked TEXT;
