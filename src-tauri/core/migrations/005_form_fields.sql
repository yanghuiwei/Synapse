-- ============================================================
-- Reqly 005_form_fields.sql —— multipart 表单的字段行单开一列
-- ------------------------------------------------------------
-- 003 给的 `body_rows` 服务的是 `urlencoded`：一张 `k=v` 的表。
-- `multipart/form-data` 也是一张表，但**每一行多一个维度** ——
-- 它可以是文本，也可以是一个文件（存路径，发送时才读盘）。
--
-- 为什么不复用 `body_rows`：那一列里躺的是「当前键值型请求体的行」，
-- 而键值型类型现在有两种。共用一列的话，从 urlencoded 切到 form
-- 会把上一种的行原样带过去（表格里显示着 urlencoded 的键值对，
-- 用户以为那是 form 的内容），切回来又反过来。003 的注释里
-- 已经写明「multipart 落地时必须改成按类型分槽」——这就是那一步。
--
-- 为什么行里要存路径而不是文件内容：大文件不该被搬进内存再走一遍 IPC，
-- 而发送只需读一次盘。路径在发送前一刻解析（占位符也一样）。
--
-- 存量库跑到这里取默认 `[]`；前端读到时表现为「这个请求还没有字段」，
-- 与升级前一致（那时根本选不了 multipart）。
-- ============================================================

ALTER TABLE request ADD COLUMN form_fields TEXT NOT NULL DEFAULT '[]';
